from .role import RoleConfig

# 分类顺序（前端「场景选择」页沿用此顺序）
CATEGORY_ORDER = ["academic", "emotion", "relationship", "family", "career", "risk"]

CATEGORY_LABELS = {
    "academic": "学业困难",
    "emotion": "情绪困扰",
    "relationship": "人际关系",
    "family": "家庭困境",
    "career": "就业迷茫",
    "risk": "危机识别与联动",
}


def category_label(key: str) -> str:
    return CATEGORY_LABELS.get(key, key)


def public_summary(c: dict) -> dict:
    """列表页公开摘要：化名 / 基本资料 / 处境 / 训练主题 / 时长。"""
    return {
        "id": c.get("id", ""),
        "category": c.get("category", ""),
        "name": c.get("name", ""),
        "grade_major": c.get("grade_major", ""),
        "tagline": c.get("tagline", ""),
        "quote": c.get("quote", ""),
        "training_focus": c.get("training_focus", ""),
        "duration": c.get("duration", ""),
        "avatar": c.get("avatar", ""),
    }


def public_detail(c: dict) -> dict:
    """详情页公开信息：在摘要基础上补充已知情况 + 训练目标。"""
    d = public_summary(c)
    d["public_background"] = c.get("public_background", "")
    d["goals"] = c.get("goals", [])
    return d


def case_to_role(c: dict) -> RoleConfig:
    """案例 → 角色配置：私有层进 system prompt，供 /ws/chat、/ws/voice 共用。"""
    return RoleConfig(
        name=c.get("name", ""),
        grade_major=c.get("grade_major", ""),
        scenario=category_label(c.get("category", "")),
        hidden_background=c.get("hidden_background", ""),
        speech_style=c.get("speech_style", ""),
        notes=c.get("public_background", ""),
        branches=c.get("branches", []),
        opening=c.get("opening", ""),
    )


